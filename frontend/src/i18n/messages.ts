export function translate(language: Language, key: string, values: Record<string, string | number> = {}): string {
  const message = language === 'fa' ? persian[key] ?? key : key
  return message.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match))
}
export function localeFor(language: Language) { return language === 'fa' ? 'fa-IR' : 'en-US' }
